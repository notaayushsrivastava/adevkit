import shutil
from pathlib import Path
from typing import Optional

def generate_prd_template(
    target_dir: Path,
    project_name: str,
    overview: str = "",
    target_users: str = "",
    core_features: str = "",
) -> Path:
    """Generate a structured, professional PRD.md."""
    target_dir = Path(target_dir)
    file_path = target_dir / "PRD.md"

    ov = overview.strip() or f"High-level vision and objectives for {project_name}."
    users = target_users.strip() or "Primary target users and stakeholders."
    features = core_features.strip() or "- Core Feature 1\n- Core Feature 2\n- Core Feature 3"

    content = f"""# Product Requirements Document (PRD): {project_name}

**Status**: Draft / In Progress  
**Author**: Aayush  
**Last Updated**: Auto-generated by Aayush's DevKit  

---

## 1. Executive Summary & Problem Statement
### Overview
{ov}

### The Problem
- Clearly define the pain points this project addresses.
- What friction exists in current alternatives?

---

## 2. Target Audience & Personas
### Target Users
{users}

### Key User Scenarios
1. **Scenario A**: Primary day-to-day workflow.
2. **Scenario B**: Edge-case or administrator workflow.

---

## 3. Core Functional Requirements (MVP)
{features}

### Requirements Breakdown
| ID | Feature | Priority | Description | Acceptance Criteria |
|---|---|---|---|---|
| F-01 | Initial Scaffolding | P0 | Project bootstraps cleanly with zero errors | Commands run cleanly |
| F-02 | Core Logic | P0 | Core business logic implementation | Tests pass |
| F-03 | Polish & Verification | P1 | UI / API polishing and edge cases | Verified manually & automated |

---

## 4. Technical & Non-Functional Requirements
- **Performance**: Instantaneous responses, lean bundle size.
- **Reliability**: Graceful error handling and robust tests.
- **Security**: No hardcoded secrets; use environment variables (`.env`).
- **Maintainability**: Clear folder hierarchy, clean type definitions.

---

## 5. Milestones & Success Metrics
- [ ] **Milestone 1**: Scaffolding & environment verified.
- [ ] **Milestone 2**: Core MVP functionality completed.
- [ ] **Milestone 3**: Automated test suite passing.
- [ ] **Milestone 4**: Final documentation and deployment.
"""
    file_path.write_text(content, encoding="utf-8")
    return file_path

def import_prd_file(target_dir: Path, source_path: Path) -> Optional[Path]:
    """Copy an existing PRD file from source_path to target_dir/PRD.md."""
    target_dir = Path(target_dir)
    source_path = Path(source_path).expanduser().resolve()
    if not source_path.exists() or not source_path.is_file():
        return None
    dest_path = target_dir / "PRD.md"
    shutil.copy2(source_path, dest_path)
    return dest_path
